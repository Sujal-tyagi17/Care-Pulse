interface IconProps {
  name: string;
  className?: string;
  /** Kept for call sites converted from Material Symbols; filled icons render as regular strokes. */
  style?: React.CSSProperties;
  strokeWidth?: number;
}

/** Sized by font-size (1em), so existing text-sm / text-lg classes keep working. */
export const Icon: React.FC<IconProps> = ({ name, className = '', strokeWidth = 2 }) => {
  const Cmp = ICONS[name] ?? Circle;
  return <Cmp aria-hidden="true" strokeWidth={strokeWidth} className={`inline-block w-[1em] h-[1em] shrink-0 ${className}`} />;
};
